import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseNodeEnginePolicy } from '@kb-labs/plugin-contracts/node-engine-policy';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootArgument = process.argv.indexOf('--root');
const root = path.resolve(rootArgument === -1 ? path.join(scriptDirectory, '../../..') : process.argv[rootArgument + 1]);
const check = process.argv.includes('--check');
const manifestPath = path.join(root, 'package.json');
const outputPath = path.join(root, 'tools/clikit/toolchain/node_policy_gen.go');
const outputJsonPath = path.join(root, 'tools/clikit/toolchain/node_policy_gen.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
const { requiredMajor } = parseNodeEnginePolicy(manifest.engines?.node);
const [packageManagerName, pnpmVersion] = String(manifest.packageManager ?? '').split('@');
if (packageManagerName !== 'pnpm' || !pnpmVersion) throw new Error('package.json must pin pnpm as packageManager');
const pnpmMajor = Number(pnpmVersion.split('.')[0]);
const generated = `// Code generated by tools/clikit/toolchain/generate-node-policy.mjs from package.json; DO NOT EDIT.\n\npackage toolchain\n\nconst (\n\tSupportedNodeMajor = ${requiredMajor}\n\tSupportedPnpmMajor = ${pnpmMajor}\n\tSupportedPnpm = "${pnpmVersion}"\n)\n`;
const generatedJson = `${JSON.stringify({
  requiredMajor,
  nodeBaseImage: `node:${requiredMajor}-bookworm`,
  nodeBaseImageArgument: 'KB_JOURNEY_NODE_BASE_IMAGE',
}, null, 2)}\n`;

if (check) {
  let currentGo;
  let currentJson;
  try {
    currentGo = await readFile(outputPath, 'utf8');
  } catch {
    process.stderr.write(`generated Go Node policy is missing: ${outputPath}; run go generate ./toolchain\n`);
    process.exitCode = 1;
  }
  try {
    currentJson = await readFile(outputJsonPath, 'utf8');
  } catch {
    process.stderr.write(`generated JSON Node policy is missing: ${outputJsonPath}; run go generate ./toolchain\n`);
    process.exitCode = 1;
  }
  if (currentGo !== undefined && currentGo !== generated) {
    process.stderr.write(`generated Go Node policy is stale for ${manifest.engines.node}; run go generate ./toolchain\n`);
    process.exitCode = 1;
  }
  if (currentJson !== undefined && currentJson !== generatedJson) {
    process.stderr.write(`generated JSON Node policy is stale for ${manifest.engines.node}; run go generate ./toolchain\n`);
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated, 'utf8');
  await writeFile(outputJsonPath, generatedJson, 'utf8');
}
