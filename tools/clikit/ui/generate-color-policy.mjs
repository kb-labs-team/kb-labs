#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { colorPolicy } from '../../../core/plugin-contracts/src/color-policy.mjs';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootOption = process.argv.indexOf('--root');
const root = path.resolve(rootOption === -1 ? path.join(scriptDirectory, '../../..') : process.argv[rootOption + 1]);
const check = process.argv.includes('--check');
const forceColorInteger = colorPolicy.forceColorInteger;
if (forceColorInteger.minimum !== 1 || forceColorInteger.digits.length === 0 || forceColorInteger.digits.some((digit, index) => digit.length !== 1 || !/[0-9]/.test(digit) || forceColorInteger.digits.indexOf(digit) !== index)) {
  throw new Error('FORCE_COLOR integer grammar must declare unique ASCII digits with a minimum of 1.');
}
const forceColorDigits = forceColorInteger.digits.join('');
const forceColorPositiveDigits = forceColorInteger.digits.filter((digit) => Number(digit) >= forceColorInteger.minimum).join('');
const forceColorPattern = `^[${forceColorDigits}]+$`;
const installers = [
  'tools/kb-create/install.sh',
  'tools/kb-dev/install.sh',
  'tools/kb-deploy/install.sh',
  'tools/kb-devkit/install.sh',
  'tools/kb-monitor/install.sh',
];
const outputs = [
  ['tools/clikit/ui/color_policy_gen.go', renderGo('ui')],
  ['tools/clikit/ui/color_policy_cases_test.go', renderGoCases('ui')],
  ['tools/clikit/ui/color_policy_cases.sh', renderShellCases()],
  ['templates/go-binary/cmd/color_policy_gen.go', renderGo('cmd')],
  ['templates/go-binary/cmd/color_policy_cases_test.go', renderGoCases('cmd')],
  ['tools/kb-dev/cmd/color_policy_cases_test.go', renderGoCases('cmd')],
];
const startMarker = '# BEGIN GENERATED COLOR POLICY';
const endMarker = '# END GENERATED COLOR POLICY';
let failed = false;

for (const [relativePath, expected] of outputs) {
  const target = path.join(root, relativePath);
  awaitGenerated(target, expected);
}
for (const relativePath of installers) {
  const target = path.join(root, relativePath);
  let source;
  try {
    source = readFileSync(target, 'utf8');
  } catch (error) {
    fail(`${relativePath} is missing: ${error.message}`);
    continue;
  }
  const expected = replaceGeneratedBlock(source, `${startMarker}\n${renderShell()}\n${endMarker}`);
  if (expected === undefined) {
    fail(`${relativePath} must contain exactly one generated color policy marker pair.`);
  } else {
    awaitGenerated(target, expected);
  }
}
if (failed) process.exitCode = 1;

function fail(message) {
  process.stderr.write(`${message}; run node tools/clikit/ui/generate-color-policy.mjs\n`);
  failed = true;
}

function awaitGenerated(target, expected) {
  let current;
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    current = undefined;
  }
  if (current !== undefined && current === expected) return;
  if (check) {
    fail(`${path.relative(root, target)} is stale`);
    return;
  }
  writeFileSync(target, expected, 'utf8');
}

function replaceGeneratedBlock(source, block) {
  const lines = source.split(/\r?\n/);
  const starts = lines.flatMap((line, index) => line === startMarker ? [index] : []);
  const ends = lines.flatMap((line, index) => line === endMarker ? [index] : []);
  if (starts.length !== 1 || ends.length !== 1 || starts[0] >= ends[0]) return undefined;
  lines.splice(starts[0], ends[0] - starts[0] + 1, ...block.split('\n'));
  return lines.join('\n');
}

function renderGo(packageName) {
  const body = colorPolicy.rules.map((rule) => {
    const condition = {
      noColorNonEmpty: 'noColor != ""',
      forceColorDisabled: 'forceColorSet && (forceColor == "false" || forceColor == "0")',
      forceColorEnabled: 'forceColorSet && forceColorEnables(forceColor)',
      termDumb: 'strings.EqualFold(term, "dumb")',
      tty: 'isTTY',
    }[rule.when];
    if (!condition) throw new Error(`Unsupported color rule: ${rule.when}`);
    return `\tif ${condition} {\n\t\treturn ${rule.result}\n\t}`;
  }).join('\n');
  const templateRenderer = packageName === 'cmd' ? `\nfunc configureColor(enabled bool) {\n\tif enabled {\n\t\tlipgloss.SetColorProfile(termenv.ANSI)\n\t\treturn\n\t}\n\tlipgloss.SetColorProfile(termenv.Ascii)\n}\n` : '';
  const imports = packageName === 'cmd'
    ? 'import (\n\t"regexp"\n\t"strconv"\n\t"strings"\n\n\t"github.com/charmbracelet/lipgloss"\n\t"github.com/muesli/termenv"\n)'
    : 'import (\n\t"regexp"\n\t"strconv"\n\t"strings"\n)';
  return `// Code generated by tools/clikit/ui/generate-color-policy.mjs from core/plugin-contracts/src/color-policy.mjs; DO NOT EDIT.\n\npackage ${packageName}\n\n${imports}\n\nvar forceColorInteger = regexp.MustCompile(${quoteGo(forceColorPattern)})\nconst forceColorMinimum = ${forceColorInteger.minimum}\n\nfunc resolveColorSupport(isTTY bool, noColor, forceColor string, forceColorSet bool, term string) bool {\n${body}\n\treturn false\n}\n\nfunc forceColorEnables(value string) bool {\n\tif value == "" || value == "true" {\n\t\treturn true\n\t}\n\tif !forceColorInteger.MatchString(value) {\n\t\treturn false\n\t}\n\tlevel := strings.TrimLeft(value, "0")\n\tminimum := strconv.Itoa(forceColorMinimum)\n\treturn len(level) > len(minimum) || (len(level) == len(minimum) && level >= minimum)\n}\n${templateRenderer}`;
}

function renderGoCases(packageName) {
  const cases = colorPolicy.cases.map((item) => `\t{${quoteGo(item.name)}, ${item.tty}, ${quoteGo(item.noColor)}, ${item.forceColor !== undefined}, ${quoteGo(item.forceColor ?? '')}, ${quoteGo(item.term)}, ${item.want}},`).join('\n');
  return `// Code generated by tools/clikit/ui/generate-color-policy.mjs from core/plugin-contracts/src/color-policy.mjs; DO NOT EDIT.\n\npackage ${packageName}\n\nvar generatedColorPolicyCases = []struct {\n\tname       string\n\ttty        bool\n\tnoColor    string\n\tforceColorSet bool\n\tforceColor string\n\tterm       string\n\twant       bool\n}{\n${cases}\n}\n`;
}

function renderShellCases() {
  const cases = colorPolicy.cases.map((item) => `color_policy_case ${quoteShell(item.name)} ${item.tty} ${quoteShell(item.noColor)} ${item.forceColor !== undefined} ${quoteShell(item.forceColor ?? '')} ${quoteShell(item.term)} ${item.want}`).join('\n');
  return `# Code generated by tools/clikit/ui/generate-color-policy.mjs from core/plugin-contracts/src/color-policy.mjs; DO NOT EDIT.\n${cases}\n`;
}

function quoteGo(value) {
  return JSON.stringify(value);
}

function quoteShell(value) {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

function renderShell() {
  const body = colorPolicy.rules.map((rule) => {
    const result = rule.result ? 0 : 1;
    if (rule.when === 'termDumb') {
      return `  case "${'${TERM:-}'}" in [Dd][Uu][Mm][Bb]) return ${result} ;; esac`;
    }
    if (rule.when === 'forceColorDisabled') {
      return `  if [ "${'${FORCE_COLOR+x}'}" = x ] && { [ "${'$'}FORCE_COLOR" = false ] || [ "${'$'}FORCE_COLOR" = 0 ]; }; then return ${result}; fi`;
    }
    if (rule.when === 'forceColorEnabled') {
      return `  if [ "${'${FORCE_COLOR+x}'}" = x ]; then
    case "${'$'}FORCE_COLOR" in
      ''|true) return ${result} ;;
      false|0) ;;
      *)
        case "${'$'}FORCE_COLOR" in *[!${forceColorDigits}]*) ;;
          *) case "${'$'}FORCE_COLOR" in *[${forceColorPositiveDigits}]*) return ${result} ;; esac ;;
        esac
        ;;
    esac
  fi`;
    }
    const condition = {
      noColorNonEmpty: '[ -n "${NO_COLOR:-}" ]',
      tty: '[ -t 1 ]',
    }[rule.when];
    if (!condition) throw new Error(`Unsupported color rule: ${rule.when}`);
    return `  if ${condition}; then return ${result}; fi`;
  }).join('\n');
  return `kb_color_enabled() {\n${body}\n  return 1\n}`;
}
